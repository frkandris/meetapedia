"""Countries the crawler can search: ISO code, population, DataForSEO location.

`config/countries.yaml` is generated by `scripts/import_world.py` from Wikidata
(population, ISO 3166-1 code) and DataForSEO's own location list, and is the one
place three things are decided per country:

* **where a search runs.** DataForSEO needs a `location_code`; mapping it from
  the *language* sent every Spanish-speaking city to Spain and every English one
  to the United States. A country we cannot place is not searched at all —
  DataForSEO has no Russia, Iran, Taiwan or Hong Kong, and a search run from
  the wrong country buys the wrong results.
* **in which language.** `search_language` is the `locale` the importer writes
  for that country's cities, and so also which `search_terms` it uses.
* **in which order.** After `pipeline.country_priority`, every other country
  follows by population, largest first (see `main._settings_country_priority`).
"""
from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import yaml

# Not imported from `.config`: that module imports the pipeline, which imports
# search, which imports this — a cycle.
CONFIG_DIR = Path(__file__).resolve().parent.parent / "config"

#: Locales whose DataForSEO `language_code` is spelt differently. DataForSEO
#: has no bare "zh" — only "zh-CN" and "zh-TW".
_DATAFORSEO_LANGUAGE = {"zh": "zh-CN"}


@dataclass(frozen=True)
class Country:
    name: str
    iso2: str
    population: int
    dataforseo_location: int | None
    search_language: str


@lru_cache(maxsize=4)
def load_countries(path: Path | None = None) -> tuple[Country, ...]:
    """All countries, largest population first. Empty when the file is absent."""
    p = path or (CONFIG_DIR / "countries.yaml")
    try:
        raw = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        return ()
    out = [Country(name=str(c["name"]), iso2=str(c["iso2"]),
                   population=int(c.get("population") or 0),
                   dataforseo_location=(int(c["dataforseo_location"])
                                        if c.get("dataforseo_location") else None),
                   search_language=str(c.get("search_language") or "en"))
           for c in raw.get("countries") or []]
    out.sort(key=lambda c: -c.population)
    return tuple(out)


@lru_cache(maxsize=1)
def _by_name() -> dict[str, Country]:
    return {c.name: c for c in load_countries()}


def country(name: str) -> Country | None:
    return _by_name().get(name or "")


def population_order() -> list[str]:
    """Every known country's name, largest population first."""
    return [c.name for c in load_countries()]


def dataforseo_location(country_name: str) -> int | None:
    c = country(country_name)
    return c.dataforseo_location if c else None


def dataforseo_language(locale: str) -> str:
    lang = str(locale).split("-")[0] if "-" in str(locale) else str(locale)
    return _DATAFORSEO_LANGUAGE.get(lang, lang)
